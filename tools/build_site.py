HEARD = {"time": "frame to frame", "centroid": "brightness", "level": "level", "shape": "spectral shape"}


def presets_table(u) -> str:
    """The unit's presets on each model VAU has measured (src/vau/presets), as a table: name, line,
    tip and what moved beyond chance on the held-out seeds; the one to start at is marked."""
    import json as _json
    out = []
    for path in vau.presets.files().values():
        d = _json.loads(path.read_text(encoding="utf-8"))
        got = d["units"].get(u.id)
        if not got:
            continue
        rows = "".join(
            f'<tr><td>{esc(p["name"])}{" <span class=\"chip\">start</span>" if p["name"] == got.get("start") else ""}</td><td><code>{esc(p["line"])}</code></td>'
            f'<td>{esc(p["tip"])}</td><td>{esc(", ".join(HEARD.get(h, h) for h in (p["held_out"].get("heard") or [])) or "none beyond chance")}</td></tr>'
            for p in got["presets"])
        h = d["measured"]
        out.append(f'<h3>Presets on {esc(d["model"]["name"])}</h3>\n<p class="small">{len(got["presets"])} presets measured on {esc(d["model"]["name"])}, a {esc(d["model"].get("kind", ""))} model, '
                   f'each kept only if it broke the output on none of {got["presets"][0]["held_out"]["n"]} held-out seeds; the last column says which measures moved the same way beyond chance there. '
                   f'Presets are per model: on another model the same line can do something else.</p>\n'
                   f'<div class="table-wrap"><table><thead><tr><th>Preset</th><th>Line</th><th>What it does</th><th>Heard beyond chance</th></tr></thead><tbody>{rows}</tbody></table></div>')
    return "\n".join(out)


def card_frame(u, caption=False, hint=False) -> str:
    """A unit's strip as a host might frame it, with a plain top line (its power light and name),
    and below it the unit's card, which vau-cards.js has VAU's card.js draw, at the settings of
    the unit's example line. The card is live: its controls turn."""
    vals = example_values(u)
    tgt = vals.pop("_target", None)
    if tgt is None and u.m["targets"]:
        tgt = (u.m["targets"][0], "6")
    data = dict(vals)
    if tgt:
        data["_target"] = list(tgt)
    pre = vau.collection.prefix(u)
    name = (f'<i class="vpre">{esc(pre)}</i>' if pre else "") + esc(u.m["title"])
    bar = (f'<i class="vpre">{esc(pre)}</i>' if pre else "") + esc(u.m.get("short") or u.m["title"])   # the top bar: the short title where there is one
    wide = " wide" if u.m["category"] == "meter" else ""
    return (f'<figure class="uc{wide}"><div class="uc-strip"><div class="uc-top"><span class="uc-led"></span><b>{bar}</b></div>'
            f'<div class="uc-card" data-vau-card="{u.id}" data-values="{esc(json.dumps(data))}"></div></div>'
            + (f'<figcaption>{name}</figcaption>' if caption else "")
            + ('<p class="uc-hint">Turn a control: the figure shows GPT-2 small at the nearest setting it was run at.</p>' if hint and vau.explain.explainer(u) else "")
            + "</figure>")


def explain_slot(u) -> str:
    """Where the unit's explainer (src/vau/units/<id>.explain.js) is drawn: vau-explain.js mounts
    it into this element, with its caption and the example texts."""
    if vau.explain.explainer(u) is None:
        return ""
    return f'<div class="vx-slot" data-vau-explain="{u.id}" data-title="{esc(vau.collection.name(u))}"></div>'


def build_explain(us) -> None:
    """The explainers as VAU ships them: the runtime and every built-in unit's explainer, in one
    script (each file as it is, one after another), the runtime's styles, and the examples."""
    parts = [("vau/explain/explain.js", vau.explain.HERE / "explain.js")]
    parts += [(f"vau/units/{p.name}", p) for p in (vau.explain.explainer(u) for u in us) if p is not None]
    js = ["// Built by tools/build_site.py from the files VAU ships: " + ", ".join(n for n, _ in parts) + ".\n"]
    for name, path in parts:
        js.append(f"\n// ---- {name}\n" + path.read_text(encoding="utf-8"))
    js.append('\n// ---- the units page: draw every explainer, with the example texts\n'
              'VAUExplain.mountAll(document, { examples: "unit-texts.json" });\n')
    (DOCS / "vau-explain.js").write_text("".join(js), encoding="utf-8")
    (DOCS / "vau-explain.css").write_text((vau.explain.HERE / "explain.css").read_text(encoding="utf-8"), encoding="utf-8")
    (DOCS / "unit-texts.json").write_text((vau.explain.HERE / "examples.json").read_text(encoding="utf-8"), encoding="utf-8")


def build_look() -> None:
    """VAU's card runtime and the Core Collection's look as the package ships them, and the
    catalogue (the manifests and the collections' interfaces) as a script, so that vau-cards.js
    can have card.js draw each unit's card on the home and units pages."""
