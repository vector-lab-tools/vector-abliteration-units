def units():
    reg = vau.Registry().load()
    if reg.errors:
        raise SystemExit(f"built-in units failed to load: {reg.errors}")
    us = {u.id: u for u in reg}
    order = [us[k] for k in ORDER if k in us] + [u for k, u in sorted(us.items()) if k not in ORDER]
    return sorted(order, key=lambda u: CATEGORY_ORDER.index(u.m["category"]) if u.m["category"] in CATEGORY_ORDER else 9)   # by category first (stable)


CATEGORY_ORDER = ["effect", "fitted", "intervention", "meter", "sampler"]
CATEGORY_TITLE = {"effect": "Effects", "fitted": "Fitted", "intervention": "Interventions", "meter": "Meters", "sampler": "Samplers"}


def space_tag(u) -> str:
    """The space a unit transforms, as a small tag (SPEC 2): grouping is by category, the space is a label."""
    s = u.public()["space"]
    return f'<span class="space-tag" title="What it transforms (its space, SPEC section 4)">{esc(s)}</span>'


def num(v) -> str:
    if isinstance(v, bool):
        return str(int(v))
    if isinstance(v, float) and v.is_integer():
        return str(int(v))
    return str(v)


def example_values(u) -> dict:
    """The value each control shows: the example line's, else the default."""
    ex = line(u.m["example"]).params if u.m.get("example") else {}
    vals = {}
    for p in u.m["params"]:
        vals[p["key"]] = ex.get(p["key"], num(p["default"]) if "default" in p else "")
    for t in ("layer", "head", "attn", "mlp", "block"):
        if t in ex:
            vals["_target"] = (t, ex[t])
    return vals


