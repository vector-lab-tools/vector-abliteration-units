def fill_index(us):
    """The unit cards on the home page, between its units markers."""
    f = DOCS / "index.html"
    text = f.read_text(encoding="utf-8")
    a, b = "<!-- cards:start -->", "<!-- cards:end -->"
    by = {u.id: u for u in us}
    i, j = text.index(a) + len(a), text.index(b)
    text = text[:i] + "\n" + "\n".join("        " + card_frame(by[k], caption=True) for k in ("compressor", "multiband")) + "\n" + text[j:]
    cards = "\n".join(
        f'        <a class="card" href="units.html#{u.id}"><h3><span class="vpre">{esc(vau.collection.prefix(u))}</span>{esc(u.m["title"])}{' <span class="meterbadge">meter</span>' if u.m["category"] == "meter" else ""}</h3><p>{esc(u.m["what"])}.</p>'
        f'<span class="after">{esc(u.public()["space"])} · {"inspired by " + esc(u.m["inspired_by"]) + " · " if u.m.get("inspired_by") else ""}needs {esc(", ".join(u.needs()))}</span></a>' for u in us)
    a, b = "<!-- units:start -->", "<!-- units:end -->"
    i, j = text.index(a) + len(a), text.index(b)
    f.write_text(text[:i] + "\n" + cards + "\n" + text[j:], encoding="utf-8")


