def strip_layout(u):
    """Heights of a strip's parts before the fader: returns the y at which the fader may start."""
    y = 36 + 26                             # header, then the target select
    if u.m["targets"]:
        y += 66                             # the target's layer knob
    knobs = [p for p in u.m["params"] if p["kind"] in ("knob", "int")]
    sels = [p for p in u.m["params"] if p["kind"] == "choice" and 2 <= len(p["choices"]) <= 5]
    others = [p for p in u.m["params"] if p["kind"] in ("direction", "choice", "text", "toggle") and p not in sels]
    y += 66 * math.ceil(len(knobs) / 2) + 42 * len(others) + 62 * len(sels)
    return y


